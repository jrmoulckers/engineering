#!/usr/bin/env node
/**
 * Generate `principles/index.json` from the ratified principle files.
 *
 * The index is a derived artifact. It exists so consuming repositories and
 * tooling can resolve an `ENG-*` citation to its title, statement, status, and
 * source path without parsing Markdown. It is never a second source of truth:
 * `--check` fails when the committed index has drifted from the files.
 */

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = fileURLToPath(new URL('..', import.meta.url));
const principlesDir = join(repoRoot, 'principles');
const indexPath = join(principlesDir, 'index.json');

const FIELDS = {
  ID: 'id',
  Status: 'status',
  Statement: 'statement',
  Rationale: 'rationale',
  Evidence: 'evidence',
};

async function markdownFiles(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      found.push(...(await markdownFiles(full)));
    } else if (entry.name.endsWith('.md') && entry.name !== 'README.md') {
      found.push(full);
    }
  }
  return found;
}

function parsePrinciples(text, sourcePath) {
  const principles = [];
  // A principle is an `## ` heading followed by a `- Field: value` list.
  const sections = text.split(/^## /m).slice(1);

  for (const section of sections) {
    const lines = section.split('\n');
    const title = lines[0].trim();
    const record = { title, source: sourcePath };
    // Tracks the field a wrapped list item is still continuing onto.
    let open = null;

    for (const line of lines.slice(1)) {
      const match = /^- ([^:]+):\s*(.*)$/.exec(line);
      if (match) {
        open = FIELDS[match[1]] ?? null;
        if (open) record[open] = match[2].trim();
        continue;
      }

      // A wrapped list item continues on indented, non-empty lines. Without
      // this, a reflowed file keeps only the value's first line and truncates
      // the rest silently, which is indistinguishable from an edit.
      if (open && /^\s+\S/.test(line)) {
        record[open] = `${record[open]} ${line.trim()}`.trim();
        continue;
      }

      open = null;
    }

    if (record.id) principles.push(record);
  }

  return principles;
}

async function build() {
  const files = (await markdownFiles(principlesDir)).sort();
  const principles = [];

  for (const file of files) {
    const text = await readFile(file, 'utf8');
    const sourcePath = relative(repoRoot, file).split(sep).join('/');
    principles.push(...parsePrinciples(text, sourcePath));
  }

  principles.sort((a, b) => a.id.localeCompare(b.id));

  const duplicates = principles.map((p) => p.id).filter((id, i, all) => all.indexOf(id) !== i);
  if (duplicates.length > 0) {
    throw new Error(`Duplicate principle IDs: ${[...new Set(duplicates)].join(', ')}`);
  }

  const areas = {};
  for (const p of principles) {
    // ENG-ARCH-001 -> ARCH
    const area = p.id.split('-')[1];
    areas[area] ??= { count: 0, source: p.source };
    areas[area].count += 1;
  }

  return {
    $comment:
      'Generated by scripts/build-principles-index.mjs. Do not edit by hand; the principle Markdown files are the source of truth.',
    generator: 'scripts/build-principles-index.mjs',
    total: principles.length,
    areas,
    principles,
  };
}

export { parsePrinciples, build };

// Only run as a CLI; importing this module for tests must not touch the index.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const index = await build();
  const serialized = `${JSON.stringify(index, null, 2)}\n`;

  if (process.argv.includes('--check')) {
    let committed;
    try {
      committed = await readFile(indexPath, 'utf8');
    } catch {
      console.error(
        'principles/index.json is missing. Run: node scripts/build-principles-index.mjs',
      );
      process.exit(1);
    }
    if (committed !== serialized) {
      console.error(
        'principles/index.json has drifted from the principle files.\n' +
          'Run: node scripts/build-principles-index.mjs',
      );
      process.exit(1);
    }
    console.log(`principles/index.json is current (${index.total} principles).`);
  } else {
    await writeFile(indexPath, serialized);
    console.log(`Wrote principles/index.json (${index.total} principles).`);
  }
}
